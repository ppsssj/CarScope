"""Inventory every public Vehicle 2.3.2 domain declaration; never executes SDK APIs."""
import argparse
import hashlib
import os
from pathlib import Path
import re
import subprocess
import tempfile
import zipfile

import sys
sys.dont_write_bytecode = True
from check import SHA


def declarations(text):
    """Keep overloads and per-method annotations; never infer a missing permission."""
    rows = []
    for block in re.split(r'(?=^  public (?:abstract |static |final )*)', text, flags=re.M):
        first = block.splitlines()[0] if block else ''
        method = re.match(r'  public .*? (\w+)\((.*)\);$', first)
        if not method:
            continue
        rows.append((method[1], first.strip(), sorted(set(re.findall(r'value="(pleos\.car\.permission\.[^"]+)"', block))), 'Deprecated: true' in block))
    return rows


def inventory(aar, output):
    if hashlib.sha256(aar.read_bytes()).hexdigest() != SHA:
        raise ValueError('Vehicle 2.3.2 AAR hash mismatch')
    with zipfile.ZipFile(aar) as archive:
        jar_bytes = archive.read('classes.jar')
    with tempfile.TemporaryDirectory(prefix='carscope-public-api-') as folder:
        jar = Path(folder) / 'classes.jar'
        jar.write_bytes(jar_bytes)
        with zipfile.ZipFile(jar) as archive:
            classes = sorted(n[:-6].replace('/', '.') for n in archive.namelist()
                             if re.fullmatch(r'ai/pleos/playground/vehicle/api/[A-Z][^/$]*\.class', n))
        javap = Path(os.environ['JAVA_HOME']) / 'bin' / ('javap.exe' if os.name == 'nt' else 'javap')
        lines = ['# Vehicle 2.3.2 public domain API inventory', '',
                 f'AAR SHA-256: `{SHA}`. Generated by `python tools/component-probe/inventory.py --out docs/contracts/pleos-public-api-inventory.md`.', '',
                 'All top-level public domain interfaces in `ai.pleos.playground.vehicle.api` are enumerated, including overloads and control declarations. Permission is the method annotation; `UNDECLARED` is not permission-free. Presence does not establish runtime support. Control methods are inventory only and are never invoked by CarScope. Model/constant/listener classes are referenced by signatures, not additional vehicle domains.', '']
        total = 0
        for cls in classes:
            raw = subprocess.run([str(javap), '-v', '-classpath', str(jar), cls], capture_output=True, text=True, check=True, timeout=30).stdout
            rows = declarations(raw)
            if not rows:
                raise ValueError('No public declarations: ' + cls)
            total += len(rows)
            lines += [f'## {cls.rsplit(".", 1)[1]} ({len(rows)})', '', '| Method | Permission annotation | Deprecated | Public signature |', '| --- | --- | --- | --- |']
            for name, signature, permissions, deprecated in rows:
                lines.append(f'| `{name}` | {", ".join(p.removeprefix("pleos.car.permission.") for p in permissions) or "UNDECLARED"} | {"yes" if deprecated else "no"} | `{signature}` |')
            lines.append('')
        lines += [f'Domain interfaces: {len(classes)}. Public declarations including overloads: {total}. Runtime of unintegrated declarations: NOT_RUN.', '']
        output.write_text('\n'.join(lines), encoding='utf8')
        print(f'PASS: {len(classes)} domains, {total} declarations; static inventory only')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--aar', type=Path)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    if args.aar is None:
        cache = Path(os.environ.get('GRADLE_USER_HOME', Path.home() / '.gradle'))
        matches = list((cache / 'caches/modules-2/files-2.1/ai.pleos.playground/Vehicle/2.3.2').glob('*/*.aar'))
        if len(matches) != 1:
            raise ValueError('Exactly one Vehicle 2.3.2 AAR required')
        args.aar = matches[0]
    inventory(args.aar, args.out)
